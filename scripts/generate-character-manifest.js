"use strict";

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const root = path.resolve(__dirname, "..");
const charactersRoot = path.join(root, "assets", "characters");
const outputPath = path.join(charactersRoot, "manifest.js");
const imagePattern = /\.(?:png|jpe?g|webp)$/i;
const idleVariantPattern = /^idle_animation_([1-9]\d*)$/;

function frameNumber(fileName) {
  const matches = [...fileName.matchAll(/(\d+)/g)];
  return matches.length ? Number(matches.at(-1)[1]) : Number.MAX_SAFE_INTEGER;
}

function numericalFrameSort(left, right) {
  return frameNumber(left) - frameNumber(right) || left.localeCompare(right, "en", { numeric: true });
}

function assetVersion(filePath) {
  return crypto.createHash("sha256").update(fs.readFileSync(filePath)).digest("hex").slice(0, 12);
}

function versionedAssetPath(id, relativePath, filePath) {
  return `assets/characters/${id}/${relativePath.replace(/\\/g, "/")}?v=${assetVersion(filePath)}`;
}

function discoverAnimationNames(base) {
  const variants = fs.readdirSync(base, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && idleVariantPattern.test(entry.name))
    .map((entry) => ({ name: entry.name, index: Number(entry.name.match(idleVariantPattern)[1]) }))
    .sort((left, right) => left.index - right.index || left.name.localeCompare(right.name, "en"))
    .map((entry) => entry.name);
  return ["idle", ...variants, "idle_to_pass"];
}

function discoverCharacters(directory = charactersRoot) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .sort((left, right) => left.name.localeCompare(right.name, "en"))
    .map((entry) => {
      const id = entry.name;
      const base = path.join(directory, id);
      const portrait = path.join(base, "portrait.png");
      const animationNames = discoverAnimationNames(base);
      const animations = Object.fromEntries(animationNames.map((animation) => {
        const folder = path.join(base, animation);
        const frames = fs.existsSync(folder)
          ? fs.readdirSync(folder, { withFileTypes: true })
            .filter((frame) => frame.isFile() && imagePattern.test(frame.name))
            .map((frame) => frame.name)
            .sort(numericalFrameSort)
            .map((fileName) => versionedAssetPath(id, `${animation}/${fileName}`, path.join(folder, fileName)))
          : [];
        return [animation, frames];
      }));
      return {
        id,
        name: id.replace(/[-_]+/g, " ").replace(/\b\p{L}/gu, (letter) => letter.toLocaleUpperCase("nl")),
        portrait: fs.existsSync(portrait) ? versionedAssetPath(id, "portrait.png", portrait) : `assets/characters/${id}/portrait.png`,
        animations,
        valid: fs.existsSync(portrait) && animations.idle.length > 0
      };
    })
    .filter((character) => character.valid)
    .map(({ valid, ...character }) => character);
}

function discoverPlayableCharacters(directory = charactersRoot) {
  const contract = require('../src/playable-characters');
  return Object.entries(contract.characters).map(([id, name]) => ({ id, name,
    animations: Object.fromEntries(Object.values(contract.animations).map(({folder}) => {
      const directoryPath = path.join(directory, id, folder);
      const frames = fs.existsSync(directoryPath) ? fs.readdirSync(directoryPath, { withFileTypes: true })
        .filter(file => file.isFile() && imagePattern.test(file.name)).map(file => file.name).sort(numericalFrameSort) : [];
      if (!frames.length) throw new Error('Playable character ' + id + ': missing required animation ' + folder);
      return [folder, frames.map(file => 'assets/characters/' + id + '/' + folder + '/' + file)];
    }))
  }));
}

function writeManifest(characters = discoverCharacters()) {
  const source = `// Generated by scripts/generate-character-manifest.js. Do not edit by hand.\n` +
    `window.ATLAS_CHARACTER_MANIFEST = ${JSON.stringify({ version: 3, characters, playableCharacters: discoverPlayableCharacters() }, null, 2)};\n`;
  fs.mkdirSync(charactersRoot, { recursive: true });
  fs.writeFileSync(outputPath, source);
  return characters;
}

if (require.main === module) {
  const characters = writeManifest();
  console.log(`Atlas character manifest: ${characters.length} character(s).`);
}

module.exports = { discoverPlayableCharacters, assetVersion, discoverAnimationNames, discoverCharacters, idleVariantPattern, numericalFrameSort, writeManifest, outputPath };
